-- Corrige a visibilidade das fotos/dados públicos no diretório e unifica
-- as inscrições de push usadas pelo app e pelas funções antigas.
-- Execute uma vez no SQL Editor do Supabase.

-- 1) View pública restrita: outros membros veem apenas dados do diretório,
-- nunca e-mail, permissões ou outros campos privados do perfil.
create or replace view public.public_member_profiles
with (security_barrier = true, security_invoker = false)
as
select
  id, full_name, club_position, member_status, rider_type,
  phone, motorcycle, pilot_id, active, photo_url
from public.member_profiles
where active = true;

grant select on public.public_member_profiles to authenticated;

-- 2) Compatibilidade: o app atual grava em push_subscriptions, enquanto uma
-- versão anterior do sender consulta club_push_subscriptions. Mantemos ambas
-- sincronizadas para que os aparelhos iPhone/Android sejam encontrados.
create table if not exists public.club_push_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  endpoint text not null unique,
  subscription jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.club_push_subscriptions enable row level security;
grant select, insert, update, delete on public.club_push_subscriptions to authenticated;

drop policy if exists "Integrante vê suas assinaturas push" on public.club_push_subscriptions;
create policy "Integrante vê suas assinaturas push"
on public.club_push_subscriptions for select to authenticated
using (user_id = auth.uid());

drop policy if exists "Integrante registra suas assinaturas push" on public.club_push_subscriptions;
create policy "Integrante registra suas assinaturas push"
on public.club_push_subscriptions for insert to authenticated
with check (user_id = auth.uid());

drop policy if exists "Integrante atualiza suas assinaturas push" on public.club_push_subscriptions;
create policy "Integrante atualiza suas assinaturas push"
on public.club_push_subscriptions for update to authenticated
using (user_id = auth.uid())
with check (user_id = auth.uid());

drop policy if exists "Integrante remove suas assinaturas push" on public.club_push_subscriptions;
create policy "Integrante remove suas assinaturas push"
on public.club_push_subscriptions for delete to authenticated
using (user_id = auth.uid());

create or replace function public.sync_push_subscription_legacy()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'DELETE' then
    delete from public.club_push_subscriptions where endpoint = old.endpoint;
    return old;
  end if;

  insert into public.club_push_subscriptions(user_id, endpoint, subscription, created_at, updated_at)
  values (new.user_id, new.endpoint, new.subscription, coalesce(new.created_at, now()), coalesce(new.updated_at, now()))
  on conflict (endpoint) do update
    set user_id = excluded.user_id,
        subscription = excluded.subscription,
        updated_at = excluded.updated_at;

  return new;
end;
$$;

drop trigger if exists sync_push_subscription_legacy on public.push_subscriptions;
create trigger sync_push_subscription_legacy
after insert or update or delete on public.push_subscriptions
for each row execute function public.sync_push_subscription_legacy();

-- Copia também as inscrições já existentes para a tabela legada.
insert into public.club_push_subscriptions(user_id, endpoint, subscription, created_at, updated_at)
select user_id, endpoint, subscription, created_at, updated_at
from public.push_subscriptions
on conflict (endpoint) do update
set user_id = excluded.user_id,
    subscription = excluded.subscription,
    updated_at = excluded.updated_at;

notify pgrst, 'reload schema';
