CREATE TABLE IF NOT EXISTS public.admin_audit_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  actor_name text,
  action text NOT NULL,
  table_name text NOT NULL,
  record_id text,
  record_label text,
  old_data jsonb,
  new_data jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS admin_audit_log_created_at_idx
  ON public.admin_audit_log (created_at DESC);
CREATE INDEX IF NOT EXISTS admin_audit_log_table_name_idx
  ON public.admin_audit_log (table_name);
CREATE INDEX IF NOT EXISTS admin_audit_log_actor_id_idx
  ON public.admin_audit_log (actor_id);

ALTER TABLE public.admin_audit_log ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.is_club_audit_reader()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT lower(COALESCE(auth.jwt()->>'email','')) = 'gui.00sg@gmail.com';
$$;

DROP POLICY IF EXISTS "Audit log readable by club leadership" ON public.admin_audit_log;
DROP POLICY IF EXISTS "Audit log readable only by app developer" ON public.admin_audit_log;
CREATE POLICY "Audit log readable only by app developer"
  ON public.admin_audit_log FOR SELECT TO authenticated
  USING (public.is_club_audit_reader());

-- Não há INSERT/UPDATE/DELETE para clientes autenticados: registros entram pelo trigger.
REVOKE INSERT, UPDATE, DELETE, TRUNCATE ON public.admin_audit_log FROM anon, authenticated;
GRANT SELECT ON public.admin_audit_log TO authenticated;

CREATE OR REPLACE FUNCTION public.capture_club_audit_log()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  old_row jsonb;
  new_row jsonb;
  actor uuid;
  actor_label text;
  row_json jsonb;
  label_value text;
  id_value text;
  action_value text;
BEGIN
  actor := auth.uid();
  IF TG_OP = 'INSERT' THEN
    old_row := NULL;
    new_row := to_jsonb(NEW);
    row_json := new_row;
    action_value := 'INSERT';
  ELSIF TG_OP = 'UPDATE' THEN
    old_row := to_jsonb(OLD);
    new_row := to_jsonb(NEW);
    row_json := new_row;
    IF old_row = new_row THEN
      RETURN NEW;
    END IF;
    action_value := 'UPDATE';
  ELSE
    old_row := to_jsonb(OLD);
    new_row := NULL;
    row_json := old_row;
    action_value := 'DELETE';
  END IF;

  id_value := COALESCE(row_json->>'id', row_json->>'user_id', row_json->>'member_id', row_json->>'full_name', 'registro');
  label_value := COALESCE(row_json->>'full_name', row_json->>'title', row_json->>'name', row_json->>'email', id_value);

  SELECT p.full_name INTO actor_label
  FROM public.member_profiles p
  WHERE p.id = actor;

  INSERT INTO public.admin_audit_log
    (actor_id, actor_name, action, table_name, record_id, record_label, old_data, new_data)
  VALUES
    (actor, COALESCE(actor_label, CASE WHEN actor IS NULL THEN 'Sistema/ação externa' ELSE 'Integrante' END),
     action_value, TG_TABLE_NAME, id_value, label_value, old_row, new_row);

  IF TG_OP = 'DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END;
$$;

DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'member_profiles',
    'member_directory',
    'club_events',
    'club_documents',
    'club_announcements',
    'club_votes'
  ]
  LOOP
    IF to_regclass('public.' || t) IS NOT NULL THEN
      EXECUTE format('DROP TRIGGER IF EXISTS audit_changes ON public.%I', t);
      EXECUTE format(
        'CREATE TRIGGER audit_changes AFTER INSERT OR UPDATE OR DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.capture_club_audit_log()',
        t
      );
    END IF;
  END LOOP;
END $$;

NOTIFY pgrst, 'reload schema';
